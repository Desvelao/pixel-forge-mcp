#!/bin/sh
# pixel-forge-mcp installer
#
#   curl -fsSL https://raw.githubusercontent.com/Desvelao/pixel-forge-mcp/main/install.sh | sh
#   curl -fsSL .../install.sh | sh -s -- --register --scaffold
#
# What it does:
#   1. checks Docker and pulls the image
#   2. installs a `pixel-forge-mcp` launcher (runs the image over stdio)
#   3. optional: --register (claude mcp add), --scaffold (skill + style guide into $PWD)
#
# Env: PIXEL_FORGE_VERSION (image tag, default "latest"), PIXEL_FORGE_REF (git ref for
# --scaffold downloads, default = the version, or "main" for latest)
set -eu

REPO="Desvelao/pixel-forge-mcp"
IMAGE_BASE="ghcr.io/desvelao/pixel-forge-mcp"
VERSION="${PIXEL_FORGE_VERSION:-latest}"
BIN_DIR="${HOME}/.local/bin"
LAUNCHER_NAME="pixel-forge-mcp"
DO_REGISTER=0
DO_SCAFFOLD=0
DO_UNINSTALL=0
SCOPE=""

say()  { printf '%s\n' "$*"; }
warn() { printf 'warning: %s\n' "$*" >&2; }
die()  { printf 'error: %s\n' "$*" >&2; exit 1; }

usage() {
  cat <<USAGE
pixel-forge-mcp installer

Usage: install.sh [options]
  --register        run \`claude mcp add pixel-forge\` for the current directory
  --scope SCOPE     scope for --register: local (default), project or user
  --scaffold        copy the pixel-art skill and STYLE_GUIDE.md into the current directory
  --bin-dir DIR     where to put the launcher (default: \$HOME/.local/bin)
  --version TAG     image tag to install (default: latest)
  --uninstall       remove the launcher
  -h, --help        show this help
USAGE
}

parse_args() {
  while [ $# -gt 0 ]; do
    case "$1" in
      --register)  DO_REGISTER=1 ;;
      --scaffold)  DO_SCAFFOLD=1 ;;
      --uninstall) DO_UNINSTALL=1 ;;
      --scope)     [ $# -ge 2 ] || die "--scope needs a value"; SCOPE="$2"; shift ;;
      --bin-dir)   [ $# -ge 2 ] || die "--bin-dir needs a value"; BIN_DIR="$2"; shift ;;
      --version)   [ $# -ge 2 ] || die "--version needs a value"; VERSION="$2"; shift ;;
      -h|--help)   usage; exit 0 ;;
      *)           usage >&2; die "unknown option: $1" ;;
    esac
    shift
  done
}

check_docker() {
  command -v docker >/dev/null 2>&1 || die "Docker is required: https://docs.docker.com/get-docker/"
  docker info >/dev/null 2>&1 || die "Docker is installed but the daemon is not reachable (is it running? are you in the docker group?)"
}

pull_image() {
  say "Pulling ${IMAGE_BASE}:${VERSION} ..."
  docker pull "${IMAGE_BASE}:${VERSION}" >/dev/null \
    || die "could not pull ${IMAGE_BASE}:${VERSION} (does the tag exist? is the package public?)"
}

install_launcher() {
  mkdir -p "$BIN_DIR"
  target="${BIN_DIR}/${LAUNCHER_NAME}"
  cat > "$target" <<LAUNCHER
#!/bin/sh
# Generated by pixel-forge-mcp install.sh. Runs the MCP server over stdio.
# Host folders (override with env vars):
#   PIXEL_FORGE_DIR     sprite PNGs you edit in Pixelorama (default: \$PWD/art/work)
#   PIXEL_FORGE_EXPORT  exports, e.g. your Godot assets folder (default: \$PWD/assets/sprites)
#   PIXEL_FORGE_IMPORT  optional folder mounted read-only at /import for load_png
set -eu
WORK="\${PIXEL_FORGE_DIR:-\$PWD/art/work}"
EXPORT="\${PIXEL_FORGE_EXPORT:-\$PWD/assets/sprites}"
mkdir -p "\$WORK" "\$EXPORT"
set -- -v "\$WORK:/work" -v "\$EXPORT:/export"
if [ -n "\${PIXEL_FORGE_IMPORT:-}" ]; then
  set -- "\$@" -v "\$PIXEL_FORGE_IMPORT:/import:ro"
fi
exec docker run -i --rm -u "\$(id -u):\$(id -g)" "\$@" "${IMAGE_BASE}:${VERSION}"
LAUNCHER
  chmod +x "$target"
  say "Installed launcher: $target"
  case ":${PATH}:" in
    *":${BIN_DIR}:"*) ;;
    *) warn "${BIN_DIR} is not on your PATH; add it, or use the full path above." ;;
  esac
}

register_mcp() {
  command -v claude >/dev/null 2>&1 || { warn "claude CLI not found; skipping --register. Run later:"; print_register_hint; return 0; }
  scope_args=""
  [ -n "$SCOPE" ] && scope_args="--scope $SCOPE"
  say "Registering MCP server 'pixel-forge' ..."
  # shellcheck disable=SC2086
  claude mcp add pixel-forge $scope_args \
    -e "PIXEL_FORGE_DIR=${PWD}/art/work" \
    -e "PIXEL_FORGE_EXPORT=${PWD}/assets/sprites" \
    -- "${BIN_DIR}/${LAUNCHER_NAME}" \
    || warn "claude mcp add failed (already registered? try: claude mcp remove pixel-forge)"
}

print_register_hint() {
  say "  claude mcp add pixel-forge \\"
  say "    -e PIXEL_FORGE_DIR=\$PWD/art/work -e PIXEL_FORGE_EXPORT=\$PWD/assets/sprites \\"
  say "    -- ${BIN_DIR}/${LAUNCHER_NAME}"
}

fetch() { # fetch URL DEST (never overwrites)
  url="$1"; dest="$2"
  if [ -e "$dest" ]; then
    say "  skip (exists): $dest"
    return 0
  fi
  mkdir -p "$(dirname "$dest")"
  if command -v curl >/dev/null 2>&1; then
    curl -fsSL "$url" -o "$dest" || { rm -f "$dest"; die "download failed: $url"; }
  elif command -v wget >/dev/null 2>&1; then
    wget -qO "$dest" "$url" || { rm -f "$dest"; die "download failed: $url"; }
  else
    die "curl or wget is required for --scaffold"
  fi
  say "  created: $dest"
}

scaffold_project() {
  if [ -n "${PIXEL_FORGE_REF:-}" ]; then ref="$PIXEL_FORGE_REF"
  elif [ "$VERSION" = "latest" ]; then ref="main"
  else ref="$VERSION"; fi
  raw="https://raw.githubusercontent.com/${REPO}/${ref}"
  say "Scaffolding project in $PWD (ref: $ref) ..."
  fetch "${raw}/.claude/skills/pixel-art/SKILL.md" ".claude/skills/pixel-art/SKILL.md"
  fetch "${raw}/STYLE_GUIDE.template.md" "STYLE_GUIDE.md"
}

uninstall() {
  target="${BIN_DIR}/${LAUNCHER_NAME}"
  if [ -e "$target" ]; then rm -f "$target"; say "Removed $target"; else say "Nothing to remove at $target"; fi
  say "To also remove the image:  docker rmi ${IMAGE_BASE}:${VERSION}"
  say "To unregister:             claude mcp remove pixel-forge"
}

main() {
  parse_args "$@"
  case "$SCOPE" in ""|local|project|user) ;; *) die "--scope must be local, project or user" ;; esac
  if [ "$DO_UNINSTALL" -eq 1 ]; then uninstall; return 0; fi
  check_docker
  pull_image
  install_launcher
  [ "$DO_SCAFFOLD" -eq 1 ] && scaffold_project
  if [ "$DO_REGISTER" -eq 1 ]; then
    register_mcp
  else
    say ""
    say "Next: register it in Claude Code from your project folder:"
    print_register_hint
  fi
  say ""
  say "Done. Start a fresh \`claude\` session and run /mcp to confirm pixel-forge is connected."
}

main "$@"
